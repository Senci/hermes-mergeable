def install_fastapi_stand_in() -> None:
    class HTTPException(Exception):
        def __init__(self, status_code: int, detail: str | None = None):
            super().__init__(detail)
            self.status_code = status_code
            self.detail = detail

    class APIRouter:
        def _deco(self, _path: str, **_kw):
            return lambda fn: fn

        get = put = post = _deco

    def Query(default=None, **_kw):
        return default

    class Response:
        def __init__(self, content="", media_type=None, **_kw):
            self.body = content.encode() if isinstance(content, str) else content
            self.media_type = media_type

    mod = types.ModuleType("fastapi")
    mod.APIRouter, mod.HTTPException, mod.Query, mod.Response = APIRouter, HTTPException, Query, Response
    sys.modules["fastapi"] = mod


def load_api():
    """Import dashboard/plugin_api.py by path, as the dashboard does; stand-in when fastapi is absent."""
    try:
        import fastapi  # noqa: F401
    except ImportError:
        install_fastapi_stand_in()
    name = "mergeable_plugin_api_under_test"
    spec = importlib.util.spec_from_file_location(name, DASHBOARD / "plugin_api.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def iso_ago(days: int) -> str:
    when = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=days)
    return when.strftime("%Y-%m-%dT%H:%M:%S.000Z")


def fake_sha(seed: str) -> str:
    import hashlib

    return hashlib.sha1(seed.encode()).hexdigest()


class World:
    """A fake GitLab: projects and MRs in a JSON state file, `glab` on PATH, every argv in a log."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.bin = self.root / "bin"
        self.bin.mkdir()
        glab = self.bin / "glab"
        shutil.copy(TESTS / "fake_glab.py", glab)
        glab.chmod(glab.stat().st_mode | stat.S_IXUSR)
        self.state_path = self.root / "gitlab.json"
        self.log_path = self.root / "glab-argv.jsonl"
        self.log_path.write_text("")
        self.state = {"user": USER, "projects": {}, "mrs": {}, "branches": [], "commits": [], "created_mrs": [], "counter": 0}
        self.save()
        env = {"PATH": f"{self.bin}{os.pathsep}{os.environ['PATH']}", "FAKE_GLAB_STATE": str(self.state_path),
               "FAKE_GLAB_LOG": str(self.log_path)}
        self.patch = mock.patch.dict(os.environ, env)

    def __enter__(self):
        self.patch.start()
        return self

    def __exit__(self, *_exc):
        self.patch.stop()

    def save(self) -> None:
        self.state_path.write_text(json.dumps(self.state))

    def load(self) -> dict:
        self.state = json.loads(self.state_path.read_text())
        return self.state

    def add_project(self, pid: int, path: str, merge_method: str = "ff", has_ci: bool = True, default_branch: str = "main",
                    renovate_json: str | None = None) -> None:
        self.load()
        self.state["projects"][str(pid)] = {
            "id": pid, "path_with_namespace": path, "default_branch": default_branch, "merge_method": merge_method,
            "has_ci": has_ci, "renovate_json": renovate_json, "only_allow_merge_if_pipeline_succeeds": has_ci,
        }
        self.save()

    def add_mr(self, pid: int, iid: int, *, author: str = USER, branch: str | None = None, title: str | None = None,
               status: str = "mergeable", draft: bool = False, pipeline: str | None = "success", files: int = 3,
               description: str = "", conflicts: bool = False, target: str = "main", age: int = 5, notes: int = 0,
               sha: str | None = None, reviewers: list[str] | None = None, **knobs) -> str:
        self.load()
        project = self.state["projects"][str(pid)]
        mr = {key: None for key in SHAPES["detail_keys"]}
        sha = sha or fake_sha(f"{pid}/{iid}")
        head = None
        if pipeline is not None:
            head = {key: None for key in SHAPES["head_pipeline_keys"]}
            head.update(id=1000 * pid + iid, status=pipeline, sha=sha,
                        web_url=f"https://fake/{project['path_with_namespace']}/-/pipelines/{1000 * pid + iid}")
        mr.update(
            id=pid * 100000 + iid, iid=iid, project_id=pid, title=title or f"chore: change {iid}", description=description,
            state="opened", draft=draft, work_in_progress=draft, author={"id": 7, "username": author, "name": author},
            source_branch=branch or f"feature/{iid}", target_branch=target, sha=sha, detailed_merge_status=status,
            merge_status="can_be_merged", has_conflicts=conflicts, updated_at=iso_ago(0), created_at=iso_ago(age),
            web_url=f"https://fake/{project['path_with_namespace']}/-/merge_requests/{iid}", user_notes_count=notes,
            changes_count=str(files), head_pipeline=head, pipeline=head, rebase_in_progress=False, merge_error=None,
            labels=[], references={"full": f"{project['path_with_namespace']}!{iid}"},
            reviewers=[{"id": 20 + n, "username": name, "name": name} for n, name in enumerate(reviewers or [])],
        )
        mr["_"] = knobs
        self.state["mrs"][f"{pid}/{iid}"] = mr
        self.save()
        return sha

    def add_note(self, pid: int, iid: int, author: str, days_ago: float, *, system: bool = False, body: str = "a note") -> None:
        """One note on an MR; `days_ago` orders them (smaller is newer). The note is also counted in user_notes_count."""
        self.load()
        when = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=days_ago)
        stamp = when.strftime("%Y-%m-%dT%H:%M:%S.000Z")
        notes = self.state.setdefault("notes", {}).setdefault(f"{pid}/{iid}", [])
        notes.append({"id": len(notes) + 1, "body": body, "system": system, "created_at": stamp, "updated_at": stamp,
                      "author": {"id": 9, "username": author, "name": author}})
        self.save()

    def touch(self, pid: int, iid: int, stamp: str) -> None:
        """Move an MR's updated_at (GitLab does this on every note), so cached facts go stale."""
        self.load()
        self.state["mrs"][f"{pid}/{iid}"]["updated_at"] = stamp
        self.save()

    def add_renovate(self, pid: int, iid: int, package: str = "docker.io/library/traefik", frm: str = "v3.7.15",
                     to: str = "v3.7.16", kind: str = "patch", status: str = "mergeable", **kw) -> str:
        slug = package.replace("/", "-").replace(".", "-")
        body = RENOVATE_BODY.format(pkg=package, kind=kind, frm=frm, to=to)
        return self.add_mr(
            pid, iid, author=BOT, branch=f"renovate/{slug}-3.x", status=status,
            title=f"chore(deps): update {package} docker tag to {to}", description=body, files=1, **kw,
        )

    def mr(self, pid: int, iid: int) -> dict:
        return self.load()["mrs"][f"{pid}/{iid}"]

    def calls(self) -> list[dict]:
        return [json.loads(line) for line in self.log_path.read_text().splitlines() if line.strip()]

    def argvs(self) -> list[list[str]]:
        return [c["argv"] for c in self.calls()]

    def writes(self) -> list[dict]:
        out = []
        for call in self.calls():
            argv = call["argv"]
            if "--method" in argv[:5] and argv[argv.index("--method") + 1] != "GET":
                out.append({"method": argv[argv.index("--method") + 1], "path": argv[5], "argv": argv, "stdin": call["stdin"]})
        return out

    def assert_clean_argv(self, test) -> None:
        """No argv of any call carries `mr merge`, --rebase or merge_when_pipeline_succeeds; always `glab api`."""
        for argv in self.argvs():
            joined = " ".join(argv)
            test.assertEqual(argv[0], "api", argv)
            test.assertNotIn("mr merge", joined)
            test.assertNotIn("--rebase", joined)
            test.assertNotIn("merge_when_pipeline_succeeds", joined)


class FakeClock:
    """Virtual time for the merge waits: sleep advances now(), nothing really sleeps."""

    def __init__(self):
        self.t = 0.0
        self.slept: list[float] = []

    def sleep(self, seconds: float) -> None:
        self.slept.append(seconds)
        self.t += seconds

    def now(self) -> float:
        return self.t


class ApiCase(unittest.TestCase):
    """A temp HERMES_HOME, a World on PATH, virtual time for the waits, and every cache reset."""

    settings: dict = {}

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        root = Path(self._tmp.name)
        self.home = root / "home"
        self.home.mkdir()
        (root / "gl").mkdir()
        self.api = load_api()
        self.svc = sys.modules["mg_service"]
        self.actions = sys.modules["mg_actions"]
        self.jobs = sys.modules["mg_jobs"]
        self.store = sys.modules["mg_store"]
        self.HTTPException = sys.modules["fastapi"].HTTPException
        self.world = World(root / "gl")
        self.world.__enter__()
        self.addCleanup(self.world.__exit__)
        for patcher in (
            mock.patch.dict(os.environ, {"HERMES_HOME": str(self.home)}),
            mock.patch.object(sys.modules["mg_settings"], "read_entry", side_effect=lambda: dict(self.settings)),
            # the audit module is absent unless a test opts in: a real one would reach GitHub and the model
            mock.patch.dict(sys.modules, {"mg_audit": None}),
            mock.patch.object(self.actions, "CLOCK", FakeClock()),
            mock.patch.object(sys.modules["mg_collect"], "SETTLE_SECONDS", 0),
        ):
            patcher.start()
            self.addCleanup(patcher.stop)
        self.clock = self.actions.CLOCK
        self.svc.reset()
        self.addCleanup(self.svc.reset)
        self.addCleanup(lambda: self.world.assert_clean_argv(self))

    def standard(self) -> None:
        """Two projects: acme/bravo-infra (ff, CI) with 3 own MRs and a Renovate one, acme/echo-deploy (merge) with a colleague's."""
        self.world.add_project(1, "acme/bravo-infra")
        self.world.add_project(2, "acme/echo-deploy", merge_method="merge")
        self.world.add_mr(1, 1, title="chore: tidy", branch="feature/tidy")
        self.world.add_mr(1, 2, title="feat: new thing", status="need_rebase", branch="feature/new")
        self.world.add_renovate(1, 3)
        self.world.add_mr(2, 4, author="colleague.one", title="fix: theirs")
        self.world.add_mr(2, 5, draft=True, title="Draft: wip", branch="feature/wip")

    def mrs(self, refresh: bool = False) -> dict:
        return self.api.mrs(1 if refresh else 0)

    def item(self, ref: str, refresh: bool = False) -> dict:
        return {i["ref"]: i for i in self.mrs(refresh)["items"]}[ref]

    def finish(self, started: dict, timeout: float = 30.0) -> dict:
        """Wait for the job a write route started and return its dict."""
        return self.jobs.REGISTRY.wait(started["job_id"], timeout)

    def assert_http(self, status: int, fn, *args):
        with self.assertRaises(self.HTTPException) as ctx:
            fn(*args)
        self.assertEqual(ctx.exception.status_code, status, ctx.exception.detail)
        return ctx.exception

    def actions_log(self) -> list[dict]:
        path = self.home / "mergeable" / "actions.log"
        return [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []

    @staticmethod
    def states(job: dict) -> list[tuple[str, str]]:
        return [(s["step"], s["state"]) for s in job["steps"]]
